/** SEO-сторінка за slug категорії в БД. */
export const categorySeoBySlug = (slug: string | undefined): CategorySeo | undefined =>
  slug ? CATEGORY_SEO[slug] : undefined;

/** [slug категорії в БД, конфіг] за адресою сторінки (/roly → «роли»). */
export function categoryByPath(path: string): [string, CategorySeo] | undefined {
  return Object.entries(CATEGORY_SEO).find(([, c]) => c.path === path);
}

/** href пункту навігації: сторінка категорії, якщо є; інакше якір на головній.
 *  Клік на головній усе одно перехоплюється (скрол/фільтр) — справжня адреса потрібна пошуковику. */
export function navHref(c: { id: string; filter?: { category?: string } }): string {
  const seo = categorySeoBySlug(c.filter?.category);
  return seo ? `/${seo.path}` : `#${c.id}`;
}
