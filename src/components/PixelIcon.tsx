// Піксельна іконка з «картинки рядками»: '#' — піксель основного кольору, '+' — акцентного, решта — порожньо.
// SVG без згладжування (shape-rendering: crispEdges); та сама, що в KP/Accent.
export function PixelIcon({ rows, color, accent = color, size }: { rows: string[]; color: string; accent?: string; size: number }) {
  const w = Math.max(...rows.map((r) => r.length))
  const h = rows.length
  return (
    <svg width={size} height={(size * h) / w} viewBox={`0 0 ${w} ${h}`} shapeRendering="crispEdges" aria-hidden>
      {rows.flatMap((row, y) =>
        [...row].map((ch, x) =>
          ch === '#' || ch === '+' ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={ch === '+' ? accent : color} /> : null,
        ),
      )}
    </svg>
  )
}

